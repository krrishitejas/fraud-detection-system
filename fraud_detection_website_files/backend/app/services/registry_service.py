"""
The serving registry: the one place the service learns what it is serving.

A prediction can only be explained to somebody later if the exact things that produced
it were recorded at the time -- which model, which preprocessing, which cutoff, chosen
how and by whom. The Week 4 database design has model_version, preprocessing_version
and threshold_config entities for exactly that reason, and the Week 8 review found the
service ignoring all three: the cutoff was a constant in config.py with no record of
the model or the score scale it belonged to.

That is not a theoretical complaint. The cutoff for the model before this one sat near
0.50; for this one it is 0.065. Carrying the old constant across the model swap would
have cut recall from 0.63 to 0.33 and let roughly 930 more frauds through, with nothing
crashing and no test failing. A cutoff belongs to one trained model and to the score
scale it was chosen on, so it is stored with both.

Everything in serving/ is generated by WEEK 8/scripts/fit_serving_config.py from the
real dataset. Nothing here is hand-written.
"""
from __future__ import annotations

import json
import threading
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np
import xgboost as xgb

from app.core.config import settings
from app.utils.logging_config import get_logger

logger = get_logger(__name__)


class RegistryError(RuntimeError):
    """The serving bundle is missing or internally inconsistent."""


class ServingRegistry:
    """The active model, preprocessing, calibration, cutoff and rules, as one set.

    They are loaded together and version-stamped together because they are only
    valid together. A response that names its model but not its preprocessing is
    not reproducible: the same trees on different medians give different answers.
    """

    _instance: Optional["ServingRegistry"] = None
    _lock = threading.Lock()

    def __init__(self) -> None:
        self.is_loaded = False
        self.load_error: Optional[str] = None
        self.config: Dict[str, Any] = {}
        self.encoding: Dict[str, Dict[str, int]] = {}
        self.booster: Optional[xgb.Booster] = None
        self.iteration_range = (0, 0)
        try:
            self._load()
            self.is_loaded = True
        except Exception as exc:                                  # noqa: BLE001
            self.load_error = str(exc)
            logger.error("Serving registry failed to load: %s", exc, exc_info=True)

    @classmethod
    def get_instance(cls) -> "ServingRegistry":
        """The one registry, loaded once at startup and shared."""
        if cls._instance is None:
            with cls._lock:
                if cls._instance is None:
                    cls._instance = cls()
        return cls._instance

    # ------------------------------------------------------------------ loading

    def _load(self) -> None:
        cfg_path = settings.serving_config_path
        if not cfg_path.exists():
            # The path goes to the log for whoever is running the service; the
            # message a client sees names the file, not the server's filesystem.
            logger.error("Serving bundle missing at %s", cfg_path)
            raise RegistryError(
                "The serving bundle (serving/serving_config.json) is not present. "
                "Generate it with WEEK 8/scripts/build_serving_bundle.py."
            )
        self.config = json.loads(cfg_path.read_text(encoding="utf-8"))
        self.encoding = json.loads(
            settings.category_encoding_path.read_text(encoding="utf-8"))

        self.model_version: str = self.config["model_version"]
        self.preprocessing_version: str = self.config["preprocessing_version"]
        self.threshold_config_id: int = int(self.config["threshold_config_id"])
        self.threshold: float = float(self.config["threshold_value"])
        self.review_low: float = float(self.config["review_low"])
        self.calibration_method: str = str(self.config.get("calibration", "platt"))
        self.score_scale: str = str(self.config.get("score_scale", "calibrated"))
        self.cost_fn: float = float(self.config.get("cost_false_negative", 10.0))
        self.cost_fp: float = float(self.config.get("cost_false_positive", 1.0))
        self.platt_coef: float = float(self.config["platt_coef"])
        self.platt_intercept: float = float(self.config["platt_intercept"])
        self.all_rules: List[Dict[str, Any]] = list(self.config.get("rules", []))
        self.rules: List[Dict[str, Any]] = [r for r in self.all_rules if r["is_active"]]

        self.feature_columns: List[str] = json.loads(
            settings.feature_columns_path.read_text(encoding="utf-8"))

        # float32 throughout, and that is not a detail. Training imputed and
        # standardised in float32; doing the same arithmetic in float64 and casting
        # afterwards moves a scaled value by roughly 4e-06, which is harmless right
        # up until a boosted tree splits on a value the row now falls the other side
        # of. Across the held-out blocks that moves 2.8% of scores and flips 20
        # decisions. Matching the training dtype is what lets the service reproduce
        # the recorded validation PR-AUC to every decimal place held.
        prep = np.load(settings.preprocessing_path)
        self.medians = prep["medians"].astype(np.float32)
        self.means = prep["means"].astype(np.float32)
        stds = prep["stds"].astype(np.float32)
        self.stds = np.where(stds == 0.0, np.float32(1.0), stds)

        self._load_members()

        if len(self.feature_columns) != len(self.medians):
            raise RegistryError(
                f"the feature list holds {len(self.feature_columns)} columns but the "
                f"fitted medians hold {len(self.medians)}; the bundle is inconsistent")
        if self.booster.num_features() != len(self.feature_columns):
            raise RegistryError(
                f"the model expects {self.booster.num_features()} features but the "
                f"feature list holds {len(self.feature_columns)}")

        logger.info(
            "Registry loaded: model %s (%d member%s, combined by %s), preprocessing "
            "%s, threshold %.6f on the %s scale, %d trees in all, %d active rules.",
            self.model_version, len(self.members),
            "" if len(self.members) == 1 else "s", self.combine,
            self.preprocessing_version, self.threshold, self.score_scale,
            self.trees_in_file, len(self.rules))

    def _load_members(self) -> None:
        """Load the ensemble members, or the single model if there is no ensemble.

        The served model is a mean of several boosted models trained with different
        seeds. That is not a flourish: across seven seeds of the same configuration
        held-out PR-AUC moved by 0.0079, which is larger than most of the differences
        this project has spent its time measuring. Shipping one seed means shipping a
        draw from that spread, and the decision cutoff is chosen on a score scale
        that moves with the draw.

        The mean is taken on the LOG-ODDS scale rather than on probabilities, which
        matters for more than taste: a mean of log-odds is still one additive model,
        so TreeSHAP contributions average exactly and the explanation endpoint keeps
        meaning what it says. A mean of probabilities is not additive and every
        explanation would quietly become an approximation.
        """
        self.members: List[Dict[str, Any]] = []
        spec_path = settings.ensemble_path
        if spec_path.exists():
            spec = json.loads(spec_path.read_text(encoding="utf-8"))
            for m in spec["members"]:
                booster = xgb.Booster()
                booster.load_model(str(spec_path.parent / m["file"]))
                self.members.append({
                    "booster": booster,
                    "iteration_range": tuple(m["iteration_range"]),
                    "base_margin": float(m.get("base_margin", 0.0)),
                    "seed": m.get("seed"),
                })
            self.combine = spec.get("combine", "mean_logodds")
        else:
            booster = xgb.Booster()
            booster.load_model(str(settings.model_path))
            # Early stopping chose a round; the file still holds every tree built
            # after it, because stopping does not delete them. Scoring with all of
            # them uses trees fitted while the validation score was getting worse.
            # The sklearn wrapper honours best_iteration, the raw Booster does not,
            # so the range is applied explicitly on every call.
            best = booster.attributes().get("best_iteration")
            rng = ((0, int(best) + 1) if best is not None
                   else (0, booster.num_boosted_rounds()))
            self.members.append({"booster": booster, "iteration_range": rng,
                                 "base_margin": 0.0, "seed": None})
            self.combine = "single"

        first = self.members[0]
        self.booster = first["booster"]
        self.iteration_range = first["iteration_range"]
        self.best_iteration = first["iteration_range"][1] - 1
        self.trees_in_file = sum(int(m["booster"].num_boosted_rounds())
                                 for m in self.members)

    # ------------------------------------------------------------------ scoring

    def _margins(self, matrix: np.ndarray) -> np.ndarray:
        """The mean log-odds across the members, each over its own best rounds."""
        rows = np.ascontiguousarray(matrix, dtype=np.float32)
        total = None
        for m in self.members:
            d = xgb.DMatrix(rows)
            if m["base_margin"]:
                d.set_base_margin(np.full(len(rows), m["base_margin"],
                                          dtype=np.float32))
            z = m["booster"].predict(d, iteration_range=m["iteration_range"],
                                     output_margin=True)
            total = z if total is None else total + z
        return total / len(self.members)

    def raw_score(self, matrix: np.ndarray) -> np.ndarray:
        """Uncalibrated probability for prepared rows, best rounds only."""
        if not self.members:
            raise RegistryError("no model is loaded")
        return 1.0 / (1.0 + np.exp(-np.clip(self._margins(matrix), -40, 40)))

    def contributions(self, matrix: np.ndarray) -> np.ndarray:
        """Mean TreeSHAP contributions across the members.

        Exact, not an approximation, because the members are combined on the same
        log-odds scale TreeSHAP works on: the mean of additive explanations of a
        mean of additive models is the explanation of that mean.
        """
        rows = np.ascontiguousarray(matrix, dtype=np.float32)
        total = None
        for m in self.members:
            d = xgb.DMatrix(rows)
            # The same base margin the scorer sets. Without it the bias column
            # carries the model's own base_score instead of the offset the member
            # was actually trained and scored against, and the contributions stop
            # adding up to the score they are explaining -- which a test caught.
            if m["base_margin"]:
                d.set_base_margin(np.full(len(rows), m["base_margin"],
                                          dtype=np.float32))
            c = m["booster"].predict(d, pred_contribs=True,
                                     iteration_range=m["iteration_range"])
            total = c if total is None else total + c
        return total / len(self.members)

    def calibrate(self, raw: np.ndarray) -> np.ndarray:
        """Platt scaling on the log-odds, fitted on the first half of validation.

        Calibration is monotone, so it cannot change the ranking: PR-AUC and ROC-AUC
        are identical before and after to six decimals. What it changes is what the
        number means, which is the only reason a cost-weighted cutoff can be read off
        it at all. The cutoff in the bundle was selected on this scale and the bundle
        records which scale that was, so the two cannot drift apart.
        """
        p = np.clip(np.asarray(raw, dtype=np.float64), 1e-7, 1 - 1e-7)
        z = np.log(p / (1.0 - p))
        return 1.0 / (1.0 + np.exp(-(self.platt_coef * z + self.platt_intercept)))

    def score(self, matrix: np.ndarray) -> np.ndarray:
        """The probability the cutoff in this bundle applies to."""
        raw = self.raw_score(matrix)
        return self.calibrate(raw) if self.score_scale == "calibrated" else raw

    # ----------------------------------------------------------------- metadata

    def versions(self) -> Dict[str, Any]:
        """The three identifiers every response carries."""
        return {
            "model_version": self.model_version,
            "preprocessing_version": self.preprocessing_version,
            "threshold_config_id": self.threshold_config_id,
        }

    def threshold_record(self) -> Dict[str, Any]:
        """The cutoff with everything needed to argue about it later."""
        return {
            "threshold_config_id": self.threshold_config_id,
            "value": self.threshold,
            "review_low": self.review_low,
            "score_scale": self.score_scale,
            "calibration": self.calibration_method,
            "applies_to_model_version": self.model_version,
            "selection_method": self.config.get(
                "selection_method", "min_expected_cost_on_validation"),
            "selected_on_split": self.config.get("selected_on_split", "validation"),
            "cost_false_negative": self.cost_fn,
            "cost_false_positive": self.cost_fp,
            "cost_assumption_note": (
                "The 10:1 cost of a missed fraud against a false alarm is this "
                "project's assumption, not a figure from the literature. No paper in "
                "the supplied corpus publishes a decision threshold for IEEE-CIS. "
                "Results are reported alongside a sweep from 1x to 50x."
            ),
            "approved_by": self.config.get("approved_by", "project team"),
            "approved_at": self.config.get("approved_at"),
        }


def get_registry() -> ServingRegistry:
    """Module-level accessor, for use as a FastAPI dependency."""
    return ServingRegistry.get_instance()
